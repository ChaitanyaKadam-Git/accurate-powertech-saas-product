-- Customer flow: enquiries from first contact to commissioning, their timeline, and statements linked to them.
CREATE TABLE public.enquiry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    ref_no character varying(255) NOT NULL,
    business_line character varying(20) NOT NULL,
    customer_id bigint NOT NULL REFERENCES public.customer (id),
    title character varying(255) NOT NULL,
    capacity numeric(38,2),
    source character varying(255),
    owner_id bigint,
    stage character varying(20) NOT NULL,
    stage_date date,
    expected_value numeric(38,2),
    next_follow_up date,
    lost_reason character varying(600),
    order_no character varying(255),
    order_date date,
    order_value numeric(38,2),
    delivery_date date,
    installation_date date,
    commissioning_date date,
    warranty_until date,
    amc_until date,
    notes character varying(2000),
    created_by bigint,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone
);
CREATE INDEX idx_enquiry_tenant_stage ON public.enquiry (tenant_id, stage);
CREATE INDEX idx_enquiry_customer ON public.enquiry (customer_id);

CREATE TABLE public.enquiry_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquiry_id bigint NOT NULL,
    kind character varying(20) NOT NULL,
    stage character varying(255),
    event_date date,
    text character varying(2000),
    user_id bigint,
    user_name character varying(255),
    at timestamp(6) with time zone
);
CREATE INDEX idx_enquiry_event_enquiry ON public.enquiry_event (enquiry_id);

ALTER TABLE public.quotation ADD COLUMN enquiry_id bigint;
CREATE INDEX idx_quotation_enquiry ON public.quotation (enquiry_id);
