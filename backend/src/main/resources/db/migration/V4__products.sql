-- Masters > Products: product setups per business line, each with its parts (sub-products).
CREATE TABLE public.product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    business_line character varying(20) NOT NULL,
    name character varying(255) NOT NULL,
    code character varying(255),
    capacity numeric(38,2),
    description character varying(1000),
    active boolean NOT NULL,
    created_by bigint,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone
);
CREATE INDEX idx_product_tenant_line ON public.product (tenant_id, business_line, name);

CREATE TABLE public.product_part (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint REFERENCES public.product (id),
    sno integer NOT NULL,
    name character varying(255) NOT NULL,
    specification character varying(1000),
    make character varying(255),
    uom character varying(255),
    qty numeric(38,2),
    unit_price numeric(38,2),
    image_key character varying(255)
);
CREATE INDEX idx_product_part_product ON public.product_part (product_id);
