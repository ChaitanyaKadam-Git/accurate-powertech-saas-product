-- Masters > Templates: document templates per type (quotation, proforma, invoice) and business line, with sections.
CREATE TABLE public.doc_template (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    doc_type character varying(20) NOT NULL,
    business_line character varying(20) NOT NULL,
    name character varying(255) NOT NULL,
    is_default boolean NOT NULL,
    active boolean NOT NULL,
    pdf_title character varying(255),
    show_cover boolean NOT NULL,
    show_letter boolean NOT NULL,
    show_prices boolean NOT NULL,
    description character varying(600),
    created_by bigint,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone
);
CREATE INDEX idx_doc_template_tenant ON public.doc_template (tenant_id, doc_type, business_line);

CREATE TABLE public.template_section (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id bigint REFERENCES public.doc_template (id),
    position integer NOT NULL,
    kind character varying(20) NOT NULL,
    title character varying(255),
    content text,
    style character varying(20),
    visible boolean NOT NULL
);
CREATE INDEX idx_template_section_template ON public.template_section (template_id);

