-- Masters > Parts: each part once per company. Product parts now point at a master part and keep only their quantity.
CREATE TABLE public.part (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    name character varying(255) NOT NULL,
    category character varying(255),
    business_line character varying(20) NOT NULL,
    specification character varying(1000),
    make character varying(255),
    uom character varying(255),
    unit_price numeric(38,2),
    hsn_code character varying(255),
    image_key character varying(255),
    active boolean NOT NULL,
    created_by bigint,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone
);
CREATE INDEX idx_part_tenant_name ON public.part (tenant_id, name);

-- Move existing product parts into the master: one part per company + name + make (case-insensitive). When the same
-- part appears in products of different lines it becomes BOTH; its price and details come from the newest row.
WITH used AS (
    SELECT pr.tenant_id, pr.business_line, pp.*
    FROM public.product_part pp JOIN public.product pr ON pr.id = pp.product_id
), lines AS (
    SELECT tenant_id, lower(name) AS lname, lower(coalesce(make, '')) AS lmake, count(DISTINCT business_line) AS n
    FROM used GROUP BY 1, 2, 3
), latest AS (
    SELECT DISTINCT ON (tenant_id, lower(name), lower(coalesce(make, ''))) *
    FROM used ORDER BY tenant_id, lower(name), lower(coalesce(make, '')), id DESC
)
INSERT INTO public.part (tenant_id, name, business_line, specification, make, uom, unit_price, image_key, active, created_at, updated_at)
SELECT l.tenant_id, l.name, CASE WHEN g.n > 1 THEN 'BOTH' ELSE l.business_line END,
       l.specification, l.make, l.uom, l.unit_price, l.image_key, true, now(), now()
FROM latest l JOIN lines g ON g.tenant_id = l.tenant_id AND g.lname = lower(l.name) AND g.lmake = lower(coalesce(l.make, ''));

ALTER TABLE public.product_part ADD COLUMN part_id bigint REFERENCES public.part (id);
UPDATE public.product_part pp SET part_id = p.id
FROM public.product pr, public.part p
WHERE pr.id = pp.product_id AND p.tenant_id = pr.tenant_id
  AND lower(p.name) = lower(pp.name) AND lower(coalesce(p.make, '')) = lower(coalesce(pp.make, ''));
ALTER TABLE public.product_part ALTER COLUMN part_id SET NOT NULL;
CREATE INDEX idx_product_part_part ON public.product_part (part_id);

ALTER TABLE public.product_part DROP COLUMN name, DROP COLUMN specification, DROP COLUMN make,
    DROP COLUMN uom, DROP COLUMN unit_price, DROP COLUMN image_key;
